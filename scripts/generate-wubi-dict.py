#!/usr/bin/env python3
"""Generate the audited Wubi 86 source dictionary from pinned rime-frost data.

rime-frost keeps its Wubi tables split into a character table (with an
additional stem column) and a phrase table. Feelime only needs text/code/weight
at runtime, so this script merges both tables into one deterministic Rime
dictionary and drops the stem column. The source lives under scripts/data/;
only the host-compiled table/prism are packaged in the APK.

Inputs are the files from the already-pinned rime-frost source archive:
  cn_dicts_wb/chars.dict.yaml
  cn_dicts_wb/words.dict.yaml
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys


ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = ROOT / "scripts/data/wubi86.dict.yaml"
CODE_RE = re.compile(r"^[a-z]{1,4}$")


def data_lines(path: pathlib.Path) -> list[tuple[str, str, str]]:
    rows: list[tuple[str, str, str]] = []
    in_body = False
    for line_number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not in_body:
            if line == "...":
                in_body = True
            continue
        if not line or line.startswith("#"):
            continue
        fields = raw.split("\t")
        if len(fields) < 3:
            raise ValueError(f"{path}:{line_number}: expected text/code/weight columns")
        text, code, weight = fields[:3]
        if not text or not CODE_RE.fullmatch(code):
            raise ValueError(f"{path}:{line_number}: invalid Wubi entry {raw!r}")
        rows.append((text, code, weight))
    return rows


def render(chars: pathlib.Path, words: pathlib.Path) -> str:
    # Keep the best weight for duplicate text/code pairs. Character and phrase
    # tables can overlap; merging avoids duplicate compiled entries.
    best: dict[tuple[str, str], str] = {}
    for text, code, weight in data_lines(chars) + data_lines(words):
        key = (text, code)
        previous = best.get(key)
        if previous is None or int(weight) > int(previous):
            best[key] = weight
    lines = [
        "# Rime dictionary: wubi86",
        "# Generated by scripts/generate-wubi-dict.py from rime-frost cn_dicts_wb.",
        "# Source revision: gaboolic/rime-frost@96278d8 (GPL-3.0).",
        "---",
        "name: wubi86",
        'version: "2026-04-26"',
        "sort: by_weight",
        "columns:",
        "  - text",
        "  - code",
        "  - weight",
        "...",
    ]
    lines.extend(f"{text}\t{code}\t{weight}" for (text, code), weight in best.items())
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--chars", required=True, type=pathlib.Path)
    parser.add_argument("--words", required=True, type=pathlib.Path)
    parser.add_argument("--output", default=DEFAULT_OUTPUT, type=pathlib.Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    rendered = render(args.chars, args.words)
    if args.check:
        current = args.output.read_text(encoding="utf-8")
        if current != rendered:
            print(f"Wubi dictionary is stale: {args.output}", file=sys.stderr)
            return 1
        print(f"Wubi dictionary matches generator: {args.output}")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="utf-8")
    print(f"wrote {args.output} ({len(rendered.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
